test('mock functions', () => {
  const fn = vi.fn()
  expect(fn).toMatchSnapshot()
  fn(1, 'a')
  fn({ x: 1 })
  expect(fn).toMatchSnapshot()
  const named = vi.fn().mockName('myMock')
  named('called')
  expect(named).toMatchSnapshot()
  const returning = vi.fn(() => 'returned')
  returning()
  expect(returning).toMatchSnapshot()
})
