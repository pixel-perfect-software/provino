// Generates `src/live/terminal/vendor/width-table.ts` from the Unicode Character Database, version
// 16.0.0 (open question 11, D147):
//
//   https://www.unicode.org/Public/16.0.0/ucd/EastAsianWidth.txt
//   https://www.unicode.org/Public/16.0.0/ucd/emoji/emoji-data.txt
//
// Run: `node scripts/width-table.ts <directory holding the two files>`, from this package's root,
// after fetching them with curl into a directory of your own. The table is every code point range
// a terminal draws two columns wide: East_Asian_Width `W` and `F`, and `Emoji_Presentation`, merged
// and sorted. Nothing in this file or its output is a copy of another program's code.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const UNICODE_VERSION = '16.0.0'
const OUT = fileURLToPath(new URL('../src/live/terminal/vendor/width-table.ts', import.meta.url))

type Range = readonly [low: number, high: number]

/** The ranges of `file`'s data lines whose property (the text after the first `;`) `keep` accepts. */
function rangesOf(directory: string, file: string, keep: (property: string) => boolean): Range[] {
  const ranges: Range[] = []
  for (const line of readFileSync(join(directory, file), 'utf8').split('\n')) {
    const data = line.split('#')[0]?.trim() ?? ''
    if (data === '') continue
    const [codes, property] = data.split(';').map((part) => part.trim())
    if (codes === undefined || property === undefined || !keep(property)) continue
    const [low, high] = codes.split('..')
    const first = Number.parseInt(low ?? '', 16)
    const last = high === undefined ? first : Number.parseInt(high, 16)
    if (Number.isNaN(first) || Number.isNaN(last)) throw new Error(`bad line in ${file}: ${line}`)
    ranges.push([first, last])
  }
  return ranges
}

/** Sorts and merges overlapping or touching ranges. */
function merged(ranges: readonly Range[]): Range[] {
  const sorted = ranges.toSorted((a, b) => a[0] - b[0])
  const out: [number, number][] = []
  for (const [low, high] of sorted) {
    const last = out.at(-1)
    if (last !== undefined && low <= last[1] + 1) last[1] = Math.max(last[1], high)
    else out.push([low, high])
  }
  return out
}

const directory = process.argv[2]
if (directory === undefined) {
  process.stderr.write('usage: node scripts/width-table.ts <directory with the two UCD files>\n')
  process.exit(2)
}

const wide = merged([
  ...rangesOf(directory, 'EastAsianWidth.txt', (property) => property === 'W' || property === 'F'),
  ...rangesOf(directory, 'emoji-data.txt', (property) => property === 'Emoji_Presentation'),
])

const hex = (value: number): string => `0x${value.toString(16).toUpperCase().padStart(4, '0')}`
const rows = wide.map(([low, high]) => `  ${hex(low)}, ${hex(high)},`)

