import { posix } from 'node:path'
import {
  allowedDeps,
  entriesOf,
  type Manifest,
  type ManifestNode,
  withTestNodes,
} from './manifest.ts'
import { compare, escapeRegex, wildcardSource } from './text.ts'

/** Repo-relative paths of the files the generator owns, and of the hand-written plugin. */
export const DEPCRUISE_CONFIG: string = '.dependency-cruiser.json'
export const GENERATED_DIR: string = 'tooling/boundaries/generated'
export const BIOME_PLUGINS: string = `${GENERATED_DIR}/biome-plugins.json`
export const NEUTRAL_PLUGIN: string = 'tooling/boundaries/grit/neutral-no-dialect-name.grit'

const HEADER =
  'Generated by tooling/boundaries from packages.json. Do not edit: run `pnpm boundaries:write`.'

const DIALECT_TARGET = '^packages/dialect-[^/]+/|^@provino/dialect-'
/** The boundary lints check package code; a test may build a whole policy or name a runner. */
const NOT_TESTS: readonly string[] = ['!**/*.test.ts', '!**/*.test-d.ts']

/**
 * Every generated file, by repo-relative path, as it should be on disk. `roots` are the
 * workspace directories (`packages`, `tooling`).
 * @public
 */
export function generate(
  manifest: Manifest,
  roots: readonly string[],
): ReadonlyMap<string, string> {
  const files = new Map<string, string>()
  files.set(DEPCRUISE_CONFIG, json(depcruiseConfig(withTestNodes(manifest), roots)))
  const groups = sliceGroups(manifest)
  for (const group of groups) {
    files.set(`${GENERATED_DIR}/${group.file}`, sliceGrit(manifest, group))
  }
  files.set(BIOME_PLUGINS, json(biomePlugins(manifest, groups)))
  return files
}

interface SliceGroup {
  readonly file: string
  readonly allowed: readonly string[]
  readonly dirs: readonly string[]
}

/** Packages that may import the same slices share one plugin file. */
function sliceGroups(manifest: Manifest): readonly SliceGroup[] {
  const groups = new Map<string, { allowed: readonly string[]; dirs: string[] }>()
  for (const node of manifest.nodes) {
    if (node.parent !== undefined || node.dir === null || node.slices === 'all') continue
    const allowed = [...node.slices].sort(compare)
    const key = allowed.length === 0 ? 'none' : allowed.join('+')
    const group = groups.get(key) ?? { allowed, dirs: [] }
    group.dirs.push(`${node.dir}/**`)
    groups.set(key, group)
  }
  return [...groups.keys()].sort(compare).map((key) => {
    const group = groups.get(key) ?? { allowed: [], dirs: [] }
    return {
      file: `slice-discipline.${key}.grit`,
      allowed: group.allowed,
      dirs: group.dirs.sort(compare),
    }
  })
}

function sliceGrit(manifest: Manifest, group: SliceGroup): string {
  const allowedTypes = group.allowed.map((slice) => manifest.slices[slice] ?? slice)
  const forbidden = [
    ...manifest.wholePolicyTypes,
    ...manifest.wholePolicyValues,
    ...Object.entries(manifest.slices)
      .filter(([slice]) => !group.allowed.includes(slice))
      .map(([, type]) => type),
  ]
  const may =
    allowedTypes.length === 0
      ? 'may use no policy slice type'
      : `may use only its own policy slice type (${allowedTypes.join(', ')})`
  const message = `slice-discipline: this package ${may}; other slices, the whole Policy and the values that hand it out (neutralPolicy, resolvePolicy, …) belong to other packages. See monorepo-architecture.md, rule 3.`
  return [
    `// ${HEADER}`,
    `// Packages: ${group.dirs.join(', ')}`,
    'language js',
    '',
    // An identifier snippet matches every use of the name; the two specifier patterns catch
    // `import { X as Y }` and `export { X } from`, whose name node isn't an identifier.
    'or {',
    ...forbidden.map((name) => `  \`${name}\`,`),
    '  JsNamedImportSpecifier(name = $name),',
    '  JsExportNamedFromSpecifier(source_name = $name)',
    '} as $hit where {',
    `  or { $name <: undefined, $name <: r"(?:${forbidden.join('|')})" },`,
    `  register_diagnostic(span = $hit, message = "${message}")`,
    '}',
    '',
  ].join('\n')
}

function biomePlugins(manifest: Manifest, groups: readonly SliceGroup[]): unknown {
  const neutralDirs = manifest.nodes
    .filter((node) => node.parent === undefined && node.neutral && node.dir !== null)
    .map((node) => `${node.dir}/**`)
    .sort(compare)
  return {
    plugins: [
      {
        path: posix.relative(GENERATED_DIR, NEUTRAL_PLUGIN),
        resolutionKind: 'config',
        includes: [...neutralDirs, ...NOT_TESTS],
      },
      ...groups.map((group) => ({
        path: `./${group.file}`,
        resolutionKind: 'config',
        includes: [...group.dirs, ...NOT_TESTS],
      })),
    ],
  }
}

/** One boundary rule before the shared fields are added. */
interface RuleSpec {
  readonly name: string
  readonly comment: string
  readonly from: string
  readonly allowed: readonly string[]
}

function depcruiseConfig(manifest: Manifest, roots: readonly string[]): unknown {
  const placed = manifest.nodes.filter((node) => node.dir !== null)
  const rootsPattern = roots.map(escapeRegex).join('|')
  const workspaceTarget = `^(?:${rootsPattern})/|^@provino/|^provino(?:-|/|$)`
  return {
    $schema:
      'https://raw.githubusercontent.com/sverweij/dependency-cruiser/main/src/schema/configuration.schema.json',
    forbidden: [
      {
        name: 'neutral-no-dialect',
        comment:
          'Neutral packages never import a dialect (CLAUDE.md non-negotiable 1). A second guard beside boundary-*, so a manifest edit that allows the edge still fails.',
        severity: 'error',
        from: { path: placed.filter((node) => node.neutral).map((node) => owned(manifest, node)) },
        to: { path: DIALECT_TARGET },
      },
      ...placed.map((node) => {
        const spec = boundaryRule(manifest, node)
        return {
          name: spec.name,
          comment: spec.comment,
          severity: 'error',
          from: { path: spec.from },
          to: { path: workspaceTarget, pathNot: [...new Set(spec.allowed)] },
        }
      }),
      {
        name: 'public-entry-only',
        comment:
          'Cross-package imports use the package name and its exports, never a relative path.',
        severity: 'error',
        from: { path: `^(${rootsPattern})/([^/]+)/` },
        to: { dependencyTypes: ['local'], path: `^(?:${rootsPattern})/`, pathNot: '^$1/$2/' },
      },
      {
        name: 'not-to-unresolvable',
        comment: "Every import resolves. A deep import past a package's exports fails here.",
        severity: 'error',
        from: {},
        to: { couldNotResolve: true },
      },
      {
        name: 'no-circular',
        comment:
          'No runtime dependency cycles (monorepo-architecture.md rule 7, DECISIONS D15). A cycle made only of type imports (`import type`, `import("…").T`) erases at compile time, so it is allowed.',
        severity: 'error',
        from: {},
        to: { circular: true, viaOnly: { dependencyTypesNot: ['type-only', 'type-import'] } },
      },
    ],
    options: {
      doNotFollow: { path: 'node_modules' },
      // Build output isn't cruised. Every exports entry resolves to src/ through provino-source
      // first (`workspace-exports` checks), so no edge lands in dist/. Neither is generated or
      // scratch output: bench suites, bench records and recorder work dirs (all git-ignored).
      exclude: {
        path: '(^|/)(?:node_modules|dist|\\.tsc|\\.turbo|\\.suites|\\.results|\\.record)/',
      },
      tsPreCompilationDeps: true,
      combinedDependencies: false,
      enhancedResolveOptions: {
        exportsFields: ['exports'],
        conditionNames: ['provino-source', 'types', 'import', 'node', 'default'],
        extensions: ['.ts', '.js', '.json'],
        mainFields: ['types', 'module', 'main'],
      },
    },
  }
}

/** What a node's files may import: its own files, and each allowed node, resolved or not. */
function boundaryRule(manifest: Manifest, node: ManifestNode): RuleSpec {
  const deps = allowedDeps(manifest, node)
  const names = deps.map((dep) => dep.name).sort(compare)
  const layer = typeof node.layer === 'number' ? `layer ${node.layer}` : node.layer
  return {
    name: `boundary-${node.name
      .replace(/^@provino\//, '')
      .replaceAll('/', '-')
      .replaceAll('*', 'x')}`,
    comment: `${node.name} (${layer}, runs in ${node.runsIn}) may import only: ${
      names.length === 0 ? 'no workspace package' : names.join(', ')
    }.`,
    from: owned(manifest, node),
    allowed: [
      owned(manifest, node),
      ...deps.flatMap((dep) => [
        ...(dep.dir === null ? [] : [owned(manifest, dep)]),
        `^${wildcardSource(dep.name)}$`,
      ]),
    ],
  }
}

/** The files a node owns: its dir, minus the dirs of its subpath entries and `test/` node. */
function owned(manifest: Manifest, node: ManifestNode): string {
  const dir = dirOf(node)
  const children = entriesOf(manifest, node)
    .filter((child) => child.dir !== null)
    .map((child) => escapeRegex(dirOf(child).slice(dir.length + 1)))
  const except = children.length === 0 ? '' : `(?!(?:${children.join('|')})/)`
  return `^${wildcardSource(dir)}/${except}`
}

function dirOf(node: ManifestNode): string {
  if (node.dir === null) throw new Error(`${node.name} has no dir`)
  return node.dir
}

function json(value: unknown): string {
  return `${JSON.stringify(value, null, 2)}\n`
}
